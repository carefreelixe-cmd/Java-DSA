// STACK
// Can be implemented using:
// - ARRAY
// - ARRAYLIST
// - LINKEDLIST

// STACK is a LIFO (Last In First Out) data structure

// When using ARRAY:
// We have to check if the array is empty or full as it has a fixed size
// This is why we don't prefer it

// ARRAYLIST:
// ArrayList has variable size, so we don't have to check if it is full
// This makes it a better choice for stack implementation
